/**
 * 한 줄 헬퍼: 여러 발화를 순서대로 await 으로 재생.
 * speechManager 가 자체 큐를 갖고 있어서, 그냥 연달아 호출해도 큐로 줄세워진다.
 * 발화 간 의도적 텀이 필요할 때만 delay 인자를 준다.
 */
export async function speakSequence(
  speakFn: (text: string) => Promise<void>,
  sequence: readonly string[],
  delayMs = 0,
): Promise<void> {
  for (const line of sequence) {
    await speakFn(line);
    if (delayMs > 0) {
      await new Promise((r) => setTimeout(r, delayMs));
    }
  }
}
